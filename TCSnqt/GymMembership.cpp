// Q1) f Gym Membership Cost
// Problem Statement
// A gym offers membership plans based on the
// number of months a customer wants to enroll.
// The cost of the membership is determined as
// follows:
// Duration (Months)Cost (₹)
// ≤ 0 Invalid Input
// 1 2000
// 2 to 3 5000
// 4 to 6 9000
// > 6 15000
// Task
// Write a program that:
// • Takes an integer input months

// • Prints:
// o "Invalid Input" if months <= 0
// o Otherwise prints:
// Cost: <amount>

// Input Format
// • A single integer months
// Output Format
// • Print "Invalid Input" OR
// • Print "Cost: <amount>"

// Sample Test Cases
// Test Case 1
// Input:
// 1
// Output:
// Cost: 2000

// Test Case 2
// Input:
// 3
// Output:
// Cost: 5000

// Test Case 3
// Input:
// 5
// Output:
// Cost: 9000

// Test Case 4
// Input:
// 7
// Output:
// Cost: 15000

// Test Case 5
// Input:
// 0
// Output:
// Invalid Input